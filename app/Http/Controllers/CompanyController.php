    {
      try {
        $company = Company::create($request->all());
      }
      catch(Exception $e){
        $errorCode = 400;
        return response()->json(['error' => $errorCode, 'message' => $e->getMessage()], $errorCode);
      }

      return response()->json(['id' => $company->company_id]);
    }

